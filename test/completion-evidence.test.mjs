import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import * as runtime from '../test-support/historical-runtime.test.fixture.mjs';
import { fixtureAssessment } from '../test-support/assessments.mjs';
import { validateProofReview } from '../scripts/work-review.mjs';
const put = (root, path, data) => { mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), data); };
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), 'cyc-completion-'));
  t.after(() => { assert.equal(dirname(root), resolve(tmpdir())); assert(root.startsWith(join(resolve(tmpdir()), 'cyc-completion-'))); rmSync(root, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 }); });
  put(root, '.cyc/config.json', JSON.stringify({ verification: { commands: [{ id: 'tests', command: process.execPath, args: ['-e', "delete process.env.NODE_TEST_CONTEXT;const r=require('node:child_process').spawnSync(process.execPath,['--test'],{stdio:'inherit'});process.exit(r.status??1)"] }] } }));
  put(root, 'feature.mjs', 'export const feature = () => 0;');
  const id = runtime.startRun(root, { goal: 'Feature returns one.', playbook: 'feature', executionMode: 'standalone', evidenceVersion: 1, requirements: 'The existing feature returns one.', criteria: [{ id: 'works', description: 'Feature works', clauses: [{ id: 'endpoint', description: 'Returns one' }] }] }).runId;
  runtime.quickHandoff(root, id, { summary: 'Read the feature boundary.', assessment: fixtureAssessment(runtime.readRun(root, id), 'scout') });
  put(root, 'feature.mjs', 'export const feature = () => 1;');
  put(root, 'test/feature.test.mjs', "import test from 'node:test';import assert from 'node:assert/strict';import {feature} from '../feature.mjs';test('existing feature returns one',()=>assert.equal(feature(),1));");
  const a = { ...fixtureAssessment(runtime.readRun(root, id), 'verify'), ...fixtureAssessment(runtime.readRun(root, id), 'deliver') };
  delete a.testProof; delete a.consumerChecks;
  const input = { summary: 'Feature return observed; fixture only.', assessment: a, scenarioEvidence: [{ id: 'works', clause: 'endpoint', scenario: 'existing feature returns one', check: 'tests', receipt: 'current-verification', result: 'passed', origin: 'agent-reported', consumers: ['behavior'], evidence: 'Observed the actual feature() assertion; suite success alone is not this observation.' }] };
  return { root, id, input };
}
test('finish executes proof then returns exact bound remaining input and resumes without another proof or packet', t => {
  const savedTransport = process.env.CODEX_TOOL_CALL_ID; process.env.CODEX_TOOL_CALL_ID = 'first-invocation';
  t.after(() => savedTransport === undefined ? delete process.env.CODEX_TOOL_CALL_ID : process.env.CODEX_TOOL_CALL_ID = savedTransport);
  const { root, id, input } = fixture(t);
  const review = runtime.captureReview(root, id, { reviewer: 'self' });
  runtime.recordReview(root, id, { reviewId: review.id, identity: null, evidence: 'Inspected the current fixture return and consumer.', findings: [] });
  const first = runtime.finishRun(root, id, input);
  assert.equal(first.status, 'needs-proof-review', JSON.stringify(first)); assert.equal(first.finished, false);
  assert(first.nextAction.command.includes(`--run ${id}`)); assert.equal(first.proof.failures[0].boundary, null);
  assert(first.proof.failures[0].error.length > 0); assert.equal(runtime.readRun(root, id).verification, null);
  const remaining = JSON.parse(readFileSync(join(root, first.nextAction.inputTemplate)));
  remaining.assessment.proofReview.cases = [{ id: first.proof.failures[0].id, category: 'behavioral', reason: 'Original feature() returns 0 where this assertion expects 1.', boundary: 'Existing feature() export' }];
  process.env.CODEX_TOOL_CALL_ID = 'continuation-invocation';
  const second = runtime.finishRun(root, id, remaining);
  assert.equal(second.finished, true); assert(!second.steps.includes('prove-red'));
  const state = runtime.readRun(root, id);
  assert.equal(state.history.filter(h => h.type === 'test-proof').length, 1);
  assert.equal(state.evidence.scenarios.length, 1); assert.equal(state.evidence.scenarios[0].clause, 'endpoint');
  assert.equal(state.evidence.scenarios[0].origin, 'agent-reported');
  assert.equal(state.handoffs.find(h => h.stage === 'verify').assessment.semanticReview.receipts[0], review.id);
  assert(existsSync(join(root, second.packet.path)));
});
test('foreign/stale continuation and inadequate proof classification cannot run candidate verification', t => {
  const { root, id, input } = fixture(t); const first = runtime.finishRun(root, id, input);
  const remaining = JSON.parse(readFileSync(join(root, first.nextAction.inputTemplate)));
  assert.throws(() => runtime.finishRun(root, id, { ...remaining, continuation: { ...remaining.continuation, token: 'foreign' } }), /stale or foreign/);
  remaining.assessment.proofReview.cases = [{ id: first.proof.failures[0].id, category: 'setup', reason: 'The setup outcome remains diagnostic.' }];
  assert.throws(() => runtime.finishRun(root, id, remaining), /No decisive behavioral proof/);
  assert.equal(runtime.readRun(root, id).verification, null);
  put(root, 'feature.mjs', 'export const feature = () => 2;');
  assert.throws(() => runtime.finishRun(root, id, remaining), /stale or foreign/);
  assert.notEqual(runtime.readRun(root, id).status, 'complete');
});
test('Node file-load wrappers retain the exact importer diagnostic and cannot become behavioral proof', t => {
  const { root, id, input } = fixture(t);
  put(root, 'new-api.mjs', 'export const api=()=>1;');
  put(root, 'test/load.test.mjs', "import test from 'node:test';import {api} from '../new-api.mjs';test('new API',()=>api());");
  const first = runtime.finishRun(root, id, input);
  const load = first.proof.failures.find(f => f.name.includes('load.test.mjs'));
  assert.equal(load.hint, 'module-load'); assert.match(load.error, /Cannot find module.*new-api\.mjs.*imported from.*load\.test\.mjs/);
  assert.match(load.boundary, /new-api\.mjs$/);
  const behavior = first.proof.failures.find(f => f.name === 'existing feature returns one');
  assert.equal(behavior.hint, 'assertion'); assert.equal(behavior.boundary, null);
  const remaining = JSON.parse(readFileSync(join(root, first.nextAction.inputTemplate)));
  remaining.assessment.proofReview.cases = first.proof.failures.map(f => ({ id: f.id, category: 'behavioral', reason: 'The requested observation must reject a load wrapper as behavior.', boundary: 'Actual existing behavior' }));
  assert.throws(() => runtime.finishRun(root, id, remaining), /module-load failure/);
  assert.equal(runtime.readRun(root, id).verification, null);
});
test('Node missing named exports are observed without inventing behavioral proof', t => {
  const { root, id, input } = fixture(t);
  put(root, 'feature.mjs', 'export const feature=()=>1;export const api=()=>1;');
  put(root, 'test/load.test.mjs', "import test from 'node:test';import {api} from '../feature.mjs';test('new API',()=>api());");
  const first = runtime.finishRun(root, id, input), load = first.proof.failures.find(f => f.name.includes('load.test.mjs'));
  assert.equal(load.hint, 'module-load'); assert.match(load.error, /does not provide an export named 'api'/); assert.match(load.boundary, /feature\.mjs.*api/);
  const remaining = JSON.parse(readFileSync(join(root, first.nextAction.inputTemplate)));
  remaining.assessment.proofReview.cases = first.proof.failures.map(f => ({ id: f.id, category: 'behavioral', reason: 'The known missing export is deliberately mislabeled.', boundary: 'Existing export contract' }));
  assert.throws(() => runtime.finishRun(root, id, remaining), /module-load failure/);
  const review = remaining.assessment.proofReview;
  const state = runtime.readRun(root, id); state.testProof.failures.find(f => f.id === load.id).hint = 'unclassified'; state.testProof.failures.find(f => f.id === load.id).error = 'test failed';
  assert.throws(() => validateProofReview(state, review), /generic test-file failure/);
});
